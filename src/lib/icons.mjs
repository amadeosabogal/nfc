const attrs = (cls, size) =>
  `${cls ? ` class="${cls}"` : ""}${size ? ` width="${size}" height="${size}"` : ""} aria-hidden="true" focusable="false"`;

/** Ícono de línea por nombre. */
export const icon = (name, { size = 24, cls = "icon", stroke = 2 } = {}) => {
  const body = STROKE[name];
  if (!body) throw new Error(`Ícono desconocido: "${name}"`);
  return `<svg${attrs(cls, size)} viewBox="0 0 24 24" fill="none" stroke="currentColor" stroke-width="${stroke}" stroke-linecap="round" stroke-linejoin="round">${body}</svg>`;
};

/** Ícono relleno (estrella, WhatsApp). */
export const fillIcon = (name, { size = 24, cls = "icon" } = {}) => {
  const body = FILL[name];
  if (!body) throw new Error(`Ícono relleno desconocido: "${name}"`);
  return `<svg${attrs(cls, size)} viewBox="0 0 24 24" fill="currentColor">${body}</svg>`;
};

export const hasIcon = (name) => name in STROKE || name in FILL;

