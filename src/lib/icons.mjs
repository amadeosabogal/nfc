/** Símbolo de transmisión: un punto y tres arcos (como en la tarjeta real). */
export const broadcast = ({ cls = "" } = {}) => {
  // Medidas tomadas de la foto del producto (arcos de 47° a cada lado).
  const arcs = [35.5, 62, 87.5];
  const a = (47 * Math.PI) / 180;
  const cy = 100;
  const paths = arcs
    .map((r) => {
      const x = Math.sin(a) * r;
      const y = cy - Math.cos(a) * r;
      return `<path d="M ${(100 - x).toFixed(1)} ${y.toFixed(1)} A ${r} ${r} 0 0 1 ${(100 + x).toFixed(1)} ${y.toFixed(1)}"/>`;
    })
    .join("");
  return `<svg${attrs(cls)} viewBox="26 4 148 112"><g fill="none" stroke="currentColor" stroke-width="15" stroke-linecap="round">${paths}</g><circle cx="100" cy="${cy}" r="14" fill="currentColor"/></svg>`;
};

/** Estrellas (n) con índice --i para animar el llenado en cascada. */
